export function decodeGameName(bytes: Uint8Array): string {
  let result = "";
  for (const byte of bytes.subarray(0, 10)) {
    if (byte === 0xff) break;
    result += ENGLISH[byte] ?? "�";
  }
  return result.trimEnd();
}
